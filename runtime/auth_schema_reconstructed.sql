-- Reconstructed minimal `auth` schema for EyalMK/Draenor-Core (WoD 6.2.3).
-- Derived directly from the prepared statements authserver/worldserver emit at
-- startup (mysql_stmt_prepare dump). Column TYPES/indexes/defaults are best-effort:
-- the goal is to let statement preparation succeed so the servers reach ready
-- state and an account can be created. This is NOT the canonical Firestorm/
-- Project-Hellscream auth DB and must be replaced by the real dump before any
-- real client login is trusted (SRP6 / bnet2 login semantics depend on it).

CREATE TABLE IF NOT EXISTS `account` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `username` VARCHAR(32) NOT NULL DEFAULT '',
  `sha_pass_hash` VARCHAR(40) NOT NULL DEFAULT '',
  `sessionkey` VARCHAR(160) NOT NULL DEFAULT '',
  `v` VARCHAR(64) NOT NULL DEFAULT '0',
  `s` VARCHAR(64) NOT NULL DEFAULT '0',
  `token_key` VARCHAR(100) NOT NULL DEFAULT '',
  `bnet2_pass_hash` VARCHAR(64) NOT NULL DEFAULT '',
  `bnet2_salt` VARCHAR(64) NOT NULL DEFAULT '',
  `email` VARCHAR(255) NOT NULL DEFAULT '',
  `joindate` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `last_ip` VARCHAR(15) NOT NULL DEFAULT '127.0.0.1',
  `last_login` TIMESTAMP NULL DEFAULT NULL,
  `failed_logins` INT UNSIGNED NOT NULL DEFAULT 0,
  `locked` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `online` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `expansion` TINYINT UNSIGNED NOT NULL DEFAULT 5,
  `mutetime` BIGINT NOT NULL DEFAULT 0,
  `locale` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `recruiter` INT UNSIGNED NOT NULL DEFAULT 0,
  `os` VARCHAR(4) NOT NULL DEFAULT '',
  `service_flags` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE KEY `idx_username` (`username`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;

